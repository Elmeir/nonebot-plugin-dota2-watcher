# 【重要】写句子时不要念数据表：
#   锐评要说出结论，而不是把「字段名 + 数值」摆出来。
#   反例：`KDA 6.40`、`GPM 735`、`伤害占比 35%`、`4/3/11`、`参战率 79%`。
#   正例：`这刷钱速度有点离谱`、`全场输出最高`、`人头被你承包了`。
#   数值只在口语里本来就那么说的时候才留（`送了 12 个人头`、`15 杀`、
